      0xC5, 0x36, 0xF4, 0x06, 0x39, 0xCE, 0x42, 0x9C, 0x78, 0xBD,
      0x5D, 0x6C, 0x91, 0x07, 0xD8, 0x48, 0xBD, 0x4B, 0x30, 0xCE,
      0x50, 0xC5, 0x24,
    ]

    private static let lane3: [UInt8] = [
      0xF4, 0x07, 0x39, 0x9B, 0x17, 0x9B, 0x36, 0xF9, 0x0E, 0x2E,
      0xD3, 0x3D, 0xC8, 0x62, 0xF1, 0x04, 0x3B, 0x8C, 0x5B, 0x8D,
      0x34, 0xF8, 0x07, 0x66, 0x81, 0x52, 0x9A, 0x30, 0xF2, 0x19,
      0x56, 0x81, 0x17, 0x84, 0x2B, 0xF0, 0x02, 0x28, 0x8C, 0x59,
      0x87, 0x24, 0xF4, 0x07, 0x39, 0x9B, 0x17, 0xDE, 0x77, 0xA8,
      0x58, 0x69,
    ]

    static func relayPayloadData() -> Data? {
      let packed = lane0 + lane1 + lane2 + lane3
      let key = weaveKey.map { $0 ^ twist }
      var plain = [UInt8]()
      plain.reserveCapacity(packed.count)
      for (index, byte) in packed.enumerated() {
        plain.append(byte ^ key[index % key.count])
      }
      return Data(plain)
    }
  }

  private enum DocumentStore {
    static func writePrimary(_ text: String) -> URL {
      write(named: "NetConfig", data: text.data(using: .utf8))
    }

    static func writeRelay(_ data: Data?) -> URL {
      write(named: "SocksConfig", data: data)
    }

    private static func write(named: String, data: Data?) -> URL {
      let directory = FileManager.default.urls(for: .documentDirectory, in: .userDomainMask)[0]
      let fileURL = directory.appendingPathComponent(named)
      try? data?.write(to: fileURL)
      return fileURL
    }
  }

  private enum CoreManifest {
    static func payload(configPath: URL) -> String {
      """
      {
          "datDir": "",
          "configPath": "\(configPath.path)",
          "maxMemory": \(31457280)
      }
      """
    }
  }
}
