import Foundation

enum ProfileLedger {

  static func composeManifest() -> String {
    let blob = GroupReader.primaryBlob()
    let fileURL = DocumentStore.writePrimary(blob)
    return CoreManifest.payload(configPath: fileURL)
  }

  static func relayProfileLocation() -> String {
    let data = EmbeddedRelay.relayPayloadData()
    let fileURL = DocumentStore.writeRelay(data)
    return fileURL.path
  }

  private enum GroupReader {
    static func primaryBlob() -> String {
      let suite = UserDefaults(suiteName: ServiceDefaults.targetGroup)
      return suite?.string(forKey: ServiceDefaults.targetConfig) ?? ""
    }
  }

  private enum EmbeddedRelay {
    private static let twist: UInt8 = 0xB7

    private static let weaveKey: [UInt8] = [
      0xEB, 0x16, 0x80, 0x5F, 0xF5, 0x2A, 0xDC,
    ]

    private static let lane0: [UInt8] = [
      0x28, 0xD4, 0x59, 0x86, 0x27, 0xF1, 0x51, 0x56, 0x81, 0x17,
      0x85, 0x36, 0xE8, 0x51, 0x7C, 0x98, 0x07, 0xD8, 0x72, 0x97,
      0x18, 0x33, 0xC2, 0x5C, 0x9B, 0x77, 0xA7, 0x61, 0x7C, 0x81,
      0x47, 0x87, 0x30, 0xE9, 0x51, 0x7C, 0x99, 0x07, 0xD0, 0x72,
      0x97, 0x4B, 0x7C, 0xC0, 0x53, 0x8C, 0x30, 0xF8, 0x18, 0x2F,
      0x9B, 0x17, 0xD2,
    ]

    private static let lane1: [UInt8] = [
      0x78, 0xAC, 0x61, 0x7C, 0x81, 0x42, 0x8C, 0x32, 0xA7, 0x4B,
      0x7B, 0xD4, 0x53, 0x98, 0x65, 0x97, 0x06, 0x35, 0xD2, 0x54,
